-- 语音消息
-- ============================================================================
--
-- 加两列：语音文件地址 + 时长。
--
-- 【为什么时长要单独存，不从音频文件里读】
--
-- 因为**列表里要显示"3″"这种字样**，而读时长必须先把整个文件下载下来 ——
-- 为了显示一个数字去下载几百 KB，是明显的浪费。
-- 发的时候顺手存一下，读的时候直接用。
--
-- 音频文件复用 chat-images 那个存储空间。
-- 名字叫 images 是历史原因，但存储空间本身不关心内容是什么。
-- （单独再建一个桶的话，权限规则要再写一遍，不划算。）
--
-- 跑法：Supabase → SQL Editor → 粘进去 → Run。可以重复跑。

alter table public.messages
    add column if not exists audio_url text;

alter table public.messages
    add column if not exists audio_seconds double precision;
