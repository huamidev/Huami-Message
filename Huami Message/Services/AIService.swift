import Foundation

/// AI 服务的「插座标准」（和 ChatService 是同一个思路）。
///
/// 【为什么润色和军师是两个方法，而不是一个通用的「问 AI」？】
///
/// 因为它们背后是两套完全不同的提示词（prompt）和两套不同的产品逻辑：
///   · polish：改一句话。要求「最小改动、保留原意、只调语气」
///   · advise：判断一件事。要求「先分析对方意图，再给出可选回复方向」
///
/// 混成一个接口，将来调提示词一定会互相污染，改 A 弄坏 B。
/// 这也正是你在需求里特别强调的「两套逻辑不要混在一起」。
protocol AIService {

    /// 模块一：把一句话润色成指定风格。
    ///
    /// 返回的是**流式**结果 —— 一段一段地吐字，界面收到一段就显示一段。
    /// 注意：这里只传一句话，**不传聊天记录**。
    /// 这是你在第一步做的隐私决策：默认不读上下文。
    /// 以后如果要做「结合上下文润色」，应该新加一个方法
    /// （比如 polishWithContext），而不是偷偷改这个方法的行为 ——
    /// 这样界面上哪个入口会发上下文，一眼就能看出来。
    func polish(_ text: String, style: PolishStyle) -> AsyncStream<String>

    /// 模块二：军师。分析对方说的话，并给出回复方向。
    func advise(_ situation: String) -> AsyncStream<String>
}
