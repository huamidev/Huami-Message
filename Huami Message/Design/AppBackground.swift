import SwiftUI

/// 页面背景。
///
/// 之前这里是会缓慢流动的"极光"（深色 + 三个彩色光斑 + 毛玻璃）。
/// 现在换成浅色的、几乎看不出变化的一层灰 —— 这是 TIM 那种风格的底色。
///
/// ⚠️ 注意：**极光那套代码不是被删掉了，是换掉了。**
/// 它还在 git 历史里（commit 2edd74c）。哪天你想要"炫"一点的主题，
/// 把 AuroraBackground 找回来，再把 Theme 的颜色换回去就行 ——
/// 因为所有颜色都只在 Theme.swift 里定义，界面代码一行都不用动。
///
/// 【为什么从渐变改成了纯色】
///
/// 原来这里是 `#F2F3F5 → #EBECEF` 的极淡纵向渐变，理由是
///「纯色大面积铺开会显得死」。
///
/// 但聊天页需要在底部盖一块不透明的底，好让消息从输入栏下面"没掉"。
/// 那块底用的是 `Theme.background`（也就是渐变的**顶部**颜色），
/// 而它所在的位置，渐变已经走到接近 `#EBECEF` 了 ——
/// **两块颜色对不上，接出一条明显的亮边。**
///
/// 现象：输入栏下面横着一条又大又白的条，看起来像没做完。
/// 我一开始还以为那是"安全区没盖住"，查了半天才发现是**颜色不连续**。
///
/// 修法有两种：把那块底也改成渐变（可它只有几十磅高，接不准），
/// 或者把背景改成纯色。**选后者** ——
/// 一个 1% 的明度变化本来就没几个人看得出来，
/// 却要为此在每个"盖住背景"的地方都精确对齐，不划算。
///
/// 顺带：所有页面都用这个背景，改一处全都干净了。
struct AppBackground: View {
    var body: some View {
        Theme.background
            .ignoresSafeArea()
    }
}
